/// ==============================================================================
///  وصف الملف: lazy_data_loader.dart
/// ==============================================================================
/// واجهة عامة ومجردة (Generic Contract) لتحميل البيانات بنمط الكتالوج والتفاصيل عند الطلب:
/// 1. THeader: النموذج الخفيف لعرض القائمة السريعة (العنوان، الأيقونة، الرقم...).
/// 2. TDetail: النموذج الكامل للتفاصيل (النصوص، الأحاديث، التخريج، الشرح...).
/// ==============================================================================
library;

abstract class LazyDataLoader<THeader, TDetail> {
  /// جلب قائمة العناوين والكتالوج بسرعة فائقة في أجزاء من الملي ثانية
  Future<List<THeader>> loadHeaders();

  /// جلب التفاصيل الكاملة لعنصر محدد فقط عند الضغط عليه (On-Demand)
  Future<TDetail> loadDetails(THeader header);
}
